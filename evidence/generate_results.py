#!/usr/bin/env python3
"""Render evidence/k10-results.md from evidence/k10-stats.json.

k10-stats.json is the aggregate output of the bench3 K10 statistics script
(bench3/aegis/k10_stats.py --records runs/aegis-k10-records). This renderer
only formats; it computes nothing new. Repository maintenance script, not a
product surface.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
d = json.loads((HERE / "k10-stats.json").read_text())

L = []
add = L.append

add("# K10 results — vanilla vs guided (vs enforced)")
add("")
add("_Generated by `generate_results.py` from `k10-stats.json`. Do not edit"
    " numbers by hand._")
add("")
add(f"Records: **{d['records_total']}** — {d['agentic']} agentic, "
    f"{d['singleshot']} single-shot; k={d['k']} repetitions per "
    f"(task × model × arm) cell; {len(d['models'])} models; "
    f"{len(d['tasks'])} tasks; 3 arms (vanilla / guided / enforced).")
add("")

add("## Resolution by arm")
add("")
add("| arm | agentic passed | agentic rate | single-shot passed | single-shot rate |")
add("|---|---|---|---|---|")
for arm in ("vanilla", "guided", "enforced"):
    a = d["per_arm"][arm]["agentic"]
    s = d["per_arm"][arm]["singleshot"]
    add(f"| {arm} | {a['passed']}/{a['n']} | {a['passed']/a['n']:.1%} "
        f"| {s['passed']}/{s['n']} | {s['passed']/s['n']:.1%} |")
add("")

add("## Where vanilla → guided differs (per-cell pass-rate deltas, k=10)")
add("")
add("All cells with a nonzero paired delta. Cells not listed are identical"
    " between the arms.")
add("")
add("| task | model | vanilla | guided | delta |")
add("|---|---|---|---|---|")
neg = 0
for p in d["paired"]:
    vg = p.get("v_to_g") or {}
    delta = vg.get("delta_b_minus_a")
    if delta:
        if delta < 0:
            neg += 1
        add(f"| {p['task']} | {p['model']} | {vg['a_rate']:.1f} "
            f"| {vg['b_rate']:.1f} | {delta:+.1f} |")
add("")
add(f"Negative cells are reported ({neg} of them): the method is not free"
    " on every cell.")
add("")

add("## Method-artifact compliance by arm")
add("")
add("| arm | plan_valid | children with falsifiers | gate reverts |")
add("|---|---|---|---|")
for arm in ("vanilla", "guided", "enforced"):
    c = d["compliance"][arm]
    # The falsifier rate is computed over authored trains; with zero valid
    # trains (vanilla) it is vacuous — render n/a instead of a false 100%.
    fals = "n/a (no trains)" if c["plan_valid"] == 0 else f"{c['falsifiers']:.1%}"
    add(f"| {arm} | {c['plan_valid']:.1%} | {fals} "
        f"| {c['gate_reverts']} |")
add("")
add("`plan_valid` = the run authored a schema-valid plan train (plan +"
    " children, every child with at least one falsifier carrying a runnable"
    " check). The guided arm has **no** gate; compliance is produced by the"
    " instruction payload alone.")
add("")

add("## Cost of the method (agentic runs, bootstrap 95% CI)")
add("")
add("| arm | output tokens (mean) | wall seconds (mean) | cost USD (mean) |")
add("|---|---|---|---|")
for arm in ("vanilla", "guided", "enforced"):
    r = d["resource"][arm]
    t = r["agentic_output_tokens"]
    e = r["elapsed_seconds"]
    c = r["cost_usd"]
    add(f"| {arm} | {t['mean']:,.0f} [{t['ci95'][0]:,.0f}, {t['ci95'][1]:,.0f}] "
        f"| {e['mean']:.0f} [{e['ci95'][0]:.0f}, {e['ci95'][1]:.0f}] "
        f"| {c['mean']:.3f} [{c['ci95'][0]:.3f}, {c['ci95'][1]:.3f}] |")
add("")

add("## Models and tasks")
add("")
add("Models: " + ", ".join(d["models"]) + ".")
add("")
add("Tasks: " + ", ".join(d["tasks"]) + ".")
add("")

(HERE / "k10-results.md").write_text("\n".join(L) + "\n")
print("wrote", HERE / "k10-results.md")
